#!/usr/bin/env python3
"""Install skills, the shared agent instructions, or an optional research brief. Python 3.10+, stdlib."""
from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import json
import os
import re
import secrets
import shutil
import stat
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SKILL = ROOT / "skills" / "coresearch"
HOST = ROOT / "host"
HEADER = ("<!-- Generated by coresearch from host/core.md and host/{delta} (sha256 {digest}). "
          "Edit those files, then run: python3 scripts/coresearch.py host install -->\n")
HEADER_PATTERN = re.compile(r"<!-- Generated by coresearch .*\(sha256 ([0-9a-f]{16})\)")
BACKUPS = ".local/state/coresearch/backups"
# Instruction file, host-specific addition and skills directories for each agent host, relative to the home directory.
HOSTS = {
    "claude": (".claude/CLAUDE.md", "claude.md", (".claude/skills",)),
    "codex": (".codex/AGENTS.md", "codex.md", (".codex/skills",)),
    "pi": (".pi/agent/AGENTS.md", "pi.md", (".pi/agent/skills",)),
    "opencode": (".config/opencode/AGENTS.md", "opencode.md", (".claude/skills",)),  # opencode also reads Claude's
}
# Further links, keyed by the host that needs them (None: shared by every host).
LINKS = {
    None: {".local/bin/glm-delegate": "skills/glm-delegate/scripts/glm-delegate"},
    "codex": {".codex/rules/coresearch.rules": "host/codex.rules"},
}
# Skills kept in other repositories, such as private tools' skills, and linked into every host like the bundled ones:
# a JSON object of skill name to directory ("~/" is the home directory) in this machine's configuration, so they stay
# out of this repository.
EXTERNAL_SKILLS = ".config/coresearch/skills.json"
SKILL_NAME = re.compile(r"[a-z0-9][a-z0-9-]*")
# Settings merged into a host's settings file. A list gains the entries it lacks; any other value is set only where the
# key is absent, so a value the user chose, such as an effort level saved with /effort, stays. Nothing is removed.
SETTINGS = {"claude": (".claude/settings.json", "host/claude.settings.json")}


def payload(root: Path) -> dict[str, Path]:
    """Enumerate portable skill files, excluding interpreter caches."""
    result = {}
    for path in sorted(root.rglob("*")):
        relative = path.relative_to(root)
        if "__pycache__" in relative.parts or path.suffix == ".pyc":
            continue
        if path.is_symlink():
            raise ValueError(f"skill payload contains a symlink: {path}")
        if path.is_file():
            result[relative.as_posix()] = path
    if "SKILL.md" not in result:
        raise ValueError(f"missing SKILL.md: {root}")
    return result


def identical(left: dict[str, Path], right: dict[str, Path]) -> bool:
    return left.keys() == right.keys() and all(
        hashlib.sha256(left[key].read_bytes()).digest()
        == hashlib.sha256(right[key].read_bytes()).digest()
        for key in left
    )


def install(directory: Path, *, link: bool = False, dry_run: bool = False, skill: str = "coresearch") -> str:
    source = (ROOT / "skills" / skill).resolve()
    destination = directory.expanduser().resolve() / skill
    if destination == source or source in destination.parents:
        raise ValueError("installation destination is inside the source skill")
    files = payload(source)
    if destination.is_symlink():
        if link and destination.resolve() == source:
            return f"Already linked: {destination}"
        raise FileExistsError(f"preserving existing link: {destination}")
    if destination.exists():
        if not link and destination.is_dir() and identical(files, payload(destination)):
            return f"Already installed: {destination}"
        raise FileExistsError(f"preserving existing destination: {destination}")
    if dry_run:
        return f"Would {'link' if link else 'copy'} {source} -> {destination}"
    destination.parent.mkdir(parents=True, exist_ok=True)
    if link:
        destination.symlink_to(source, target_is_directory=True)
    else:
        # Exclusive creation prevents concurrent installers from sharing a target.
        destination.mkdir()
        try:
            # Publish discovery metadata last, after references and scripts exist.
            for relative in sorted(files, key=lambda name: name == "SKILL.md"):
                target = destination / relative
                target.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(files[relative], target)
        except BaseException:
            shutil.rmtree(destination)
            raise
    return f"{'Linked' if link else 'Installed'}: {destination}"


def initialize(project: Path, *, question: str | None = None, dry_run: bool = False) -> str:
    research = project.expanduser().resolve() / "research"
    if research.is_symlink():
        raise ValueError(f"preserving linked research directory: {research}")
    destination = research / "brief.md"
    if destination.exists() or destination.is_symlink():
        return f"Preserved existing brief: {destination}"
    text = (SKILL / "templates" / "brief.md").read_text(encoding="utf-8")
    text = text.replace("{{question}}", question or "State the research question.")
    if dry_run:
        return f"Would create: {destination}\n\n{text}"
    destination.parent.mkdir(parents=True, exist_ok=True)
    with destination.open("x", encoding="utf-8") as stream:
        stream.write(text)
    return f"Created: {destination}"


def skills() -> list[str]:
    return sorted(path.parent.name for path in (ROOT / "skills").glob("*/SKILL.md"))


def frontmatter_problem(text: str) -> str | None:
    """Why a SKILL.md header would not load in a strict YAML reader, or None when it would.

    Claude Code and Codex read loose headers, but pi parses strict YAML and silently drops a skill whose unquoted value
    holds ': ' or ' #' or starts with a YAML indicator; such a value must be quoted."""
    parts = text.split("---", 2)
    if not text.startswith("---") or len(parts) < 3:
        return "no front matter"
    for line in parts[1].strip("\n").splitlines():
        if not line.strip() or line[:1].isspace():
            continue  # a blank line or the indented text of a block value
        key, separator, value = line.partition(":")
        value = value.strip()
        if not separator or not re.fullmatch(r"[\w-]+", key):
            return f"not a key and value: {line!r}"
        if value[:1] in ("'", '"') or re.fullmatch(r"[|>][+-]?[1-9]?[+-]?", value):
            continue  # quoted, or a block whose text follows on indented lines
        if ": " in value or value.endswith(":") or " #" in value or value[:1] in tuple("[]{}>|*&!%@`,") \
                or value[:2] in ("- ", "? "):
            return f"quote the {key} value: strict YAML readers such as pi drop this skill"
    return None


def external_skills(home: Path) -> dict[str, Path]:
    """Skills listed in the home's EXTERNAL_SKILLS file, as name and directory; empty when there is no such file.

    A listed directory that exists must hold a SKILL.md with the same name; one that does not exist is kept, and the
    host command reports it as a missing source."""
    path = home / EXTERNAL_SKILLS
    if not path.exists():
        return {}
    data = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict) or not all(isinstance(value, str) for value in data.values()):
        raise ValueError(f"{path} must be a JSON object of skill names and directories")
    found = {}
    for name, directory in data.items():
        if not SKILL_NAME.fullmatch(name) or name in skills():
            raise ValueError(f"{path}: {name!r} is not a valid skill name or is a bundled skill")
        source = home / directory[2:] if directory.startswith("~/") else Path(directory)
        manifest = source / "SKILL.md"
        if source.exists() and not (manifest.is_file()
                                    and re.search(rf"^name:\s*{name}\s*$", manifest.read_text(encoding="utf-8"), re.M)):
            raise ValueError(f"{path}: {source} has no SKILL.md named {name}")
        if source.exists() and (problem := frontmatter_problem(manifest.read_text(encoding="utf-8"))):
            raise ValueError(f"{manifest}: {problem}")
        found[name] = source
    return found


def _digest(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()[:16]


def render(host: str) -> str:
    """Shared core followed by the host's addition, behind a header that records the body's digest."""
    delta = HOSTS[host][1]
    core = (HOST / "core.md").read_text(encoding="utf-8").rstrip("\n")
    addition = (HOST / delta).read_text(encoding="utf-8").rstrip("\n")
    body = core + "\n\n" + addition + "\n"
    return HEADER.format(delta=delta, digest=_digest(body)) + body


def _read(path: Path) -> str | None:
    try:
        return path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return None


def _instruction_state(path: Path, wanted: str) -> str:
    """missing, current, generated (an unedited earlier render) or foreign (anything else, including hand edits)."""
    if not path.exists() and not path.is_symlink():
        return "missing"
    text = _read(path) if path.is_file() else None
    if text == wanted:
        return "current"
    if text is not None:
        header, _, body = text.partition("\n")
        match = HEADER_PATTERN.match(header)
        if match and match.group(1) == _digest(body):
            return "generated"
    return "foreign"


def _link_state(path: Path, source: Path) -> str:
    if not source.exists():
        return "source missing"
    if path.exists() and path.resolve() == source.resolve():
        return "current"  # also when a parent directory already links into this checkout
    if not path.exists() and not path.is_symlink():
        return "missing"
    return "foreign"


def _host_items(home: Path, hosts: list[str]) -> list[tuple[str, Path, object]]:
    """(kind, destination, source) for every file, link and rule set the host command manages."""
    items: list[tuple[str, Path, object]] = []
    seen: set[Path] = set()

    def add(kind: str, destination: Path, source: object) -> None:
        if destination not in seen:
            seen.add(destination)
            items.append((kind, destination, source))

    external = external_skills(home)
    for host in hosts:
        instructions, _, skill_dirs = HOSTS[host]
        add("instructions", home / instructions, render(host))
        for skill_dir in skill_dirs:
            for name in skills():
                add("link", home / skill_dir / name, (ROOT / "skills" / name).resolve())
            for name, source in external.items():
                add("link", home / skill_dir / name, source.resolve() if source.exists() else source)
    for owner, links in LINKS.items():
        if owner is None or owner in hosts:
            for target, source in links.items():
                add("link", home / target, (ROOT / source).resolve())
    for host, (target, source) in SETTINGS.items():
        if host in hosts:
            add("settings", home / target, json.loads((ROOT / source).read_text(encoding="utf-8")))
    return items


Entry = tuple[tuple[str, ...], object, bool]  # key path, value, and whether the value is appended to a list


def _missing_settings(settings: Path, wanted: dict) -> tuple[dict, list[Entry]]:
    """The parsed settings and the entries it lacks; ValueError when the file is not a usable settings object.

    A wanted list contributes each string the file's list lacks. Any other wanted value counts as missing only when
    its key is absent: a value already there is the user's choice, even when it differs."""
    try:
        data = json.loads(settings.read_text(encoding="utf-8")) if settings.exists() else {}
    except OSError as error:
        raise ValueError(f"cannot read {settings}: {error}") from error
    missing: list[Entry] = []

    def walk(have: object, want: dict, path: tuple[str, ...]) -> None:
        if not isinstance(have, dict):
            raise ValueError(f"unexpected settings structure at {'.'.join(path) or 'top level'}: {settings}")
        for key, value in want.items():
            here = path + (key,)
            if isinstance(value, dict):
                walk(have.get(key, {}), value, here)
            elif isinstance(value, list):
                current = have.get(key, [])
                if not (isinstance(current, list) and all(isinstance(item, str) for item in current)):
                    raise ValueError(f"unexpected settings structure at {'.'.join(here)}: {settings}")
                missing.extend((here, item, True) for item in value if item not in current)
            elif key not in have:
                missing.append((here, value, False))

    walk(data, wanted, ())
    return data, missing


def _describe(entries: list[Entry]) -> str:
    return ", ".join(f"{'.'.join(path)} {value}" if append else f"{'.'.join(path)} = {value}" for path, value, append in entries)


def host_check(home: Path, hosts: list[str]) -> list[str]:
    """Describe every managed item that differs from this checkout; empty when all match."""
    problems = []
    for kind, destination, source in _host_items(home, hosts):
        if kind == "settings":
            try:
                missing = _missing_settings(destination, source)[1]
            except ValueError as error:
                problems.append(f"unreadable: {error}")
                continue
            if missing:
                problems.append(f"missing settings in {destination}: {_describe(missing)}")
            continue
        state = _instruction_state(destination, source) if kind == "instructions" else _link_state(destination, source)
        label = {"generated": "outdated", "foreign": "foreign" if kind == "link" else "not generated by coresearch or edited by hand"}
        if state != "current":
            problems.append(f"{label.get(state, state)}: {destination}")
    return problems


def _backup_path(home: Path, destination: Path, stamp: str) -> Path:
    """A fresh path under the backup directory, outside every directory a host scans for skills or rules."""
    try:
        relative = destination.relative_to(home)
    except ValueError:
        relative = Path(destination.name)
    candidate, suffix = home / BACKUPS / stamp / relative, 1
    while candidate.exists() or candidate.is_symlink():
        candidate, suffix = home / BACKUPS / f"{stamp}-{suffix}" / relative, suffix + 1
    return candidate


def _stage_text(target: Path, text: str) -> Path:
    """Write text to a new temporary file beside target, keeping target's permission bits when it exists."""
    descriptor, name = tempfile.mkstemp(prefix=f".{target.name}.", suffix=".coresearch-tmp", dir=target.parent)
    with os.fdopen(descriptor, "w", encoding="utf-8") as stream:
        stream.write(text)
    os.chmod(name, stat.S_IMODE(target.stat().st_mode) if target.exists() else 0o644)
    return Path(name)


def _stage_link(target: Path, source: Path) -> Path:
    staged = target.parent / f".{target.name}.{secrets.token_hex(6)}.coresearch-tmp"
    staged.symlink_to(source, target_is_directory=source.is_dir())
    return staged


def _publish(kind: str, destination: Path, source, backup: Path | None) -> None:
    """Stage the new file or link, move a foreign original to its backup, then swap the staged item in."""
    # An unedited generated file reached through a link, such as a dotfiles checkout, is rewritten in place.
    target = destination.resolve() if backup is None and kind == "instructions" and destination.is_symlink() else destination
    target.parent.mkdir(parents=True, exist_ok=True)
    staged = _stage_text(target, source) if kind == "instructions" else _stage_link(target, source)
    moved = False
    try:
        if backup:
            backup.parent.mkdir(parents=True, exist_ok=True)
            shutil.move(str(destination), backup)
            moved = True
        os.replace(staged, target)
    except BaseException:
        staged.unlink(missing_ok=True)
        if moved and not destination.exists() and not destination.is_symlink():
            shutil.move(str(backup), destination)
        raise


def _merge_settings(home: Path, settings: Path, wanted: dict, stamp: str, dry_run: bool) -> list[str]:
    try:
        data, missing = _missing_settings(settings, wanted)
    except ValueError as error:
        return [f"preserved (fix by hand): {error}"]
    if not missing:
        return []
    backup = _backup_path(home, settings, stamp) if settings.exists() else None
    action = (f"{'would ' if dry_run else ''}add settings to {settings}: {_describe(missing)}"
              + (f" (backup: {backup})" if backup else ""))
    if dry_run:
        return [action]
    for path, value, append in missing:
        node = data
        for key in path[:-1]:
            node = node.setdefault(key, {})
        if append:
            node.setdefault(path[-1], []).append(value)
        else:
            node[path[-1]] = value
    target = settings.resolve() if settings.exists() else settings  # keep a settings file that links into dotfiles
    target.parent.mkdir(parents=True, exist_ok=True)
    if backup:
        backup.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(target, backup)
    os.replace(_stage_text(target, json.dumps(data, indent=2, ensure_ascii=False) + "\n"), target)
    return [action]


def host_install(home: Path, hosts: list[str], *, replace: bool = False, dry_run: bool = False) -> list[str]:
    """Write generated instruction files, link skills and tools, and add the managed settings.

    Files and links this command did not create, and generated files edited by hand, are preserved unless replace is
    set; then they move to the backup directory first."""
    stamp = dt.datetime.now(dt.timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    actions = []
    for kind, destination, source in _host_items(home, hosts):
        if kind == "settings":
            actions.extend(_merge_settings(home, destination, source, stamp, dry_run))
            continue
        state = _instruction_state(destination, source) if kind == "instructions" else _link_state(destination, source)
        if state == "current":
            continue
        if state == "source missing":
            actions.append(f"skipped, source missing: {source}")
            continue
        foreign = state == "foreign"
        if foreign and not replace:
            actions.append(f"preserved (use --replace to back up and replace): {destination}")
            continue
        backup = _backup_path(home, destination, stamp) if foreign else None
        verb = "replace" if foreign else "write" if kind == "instructions" else "link"
        actions.append(f"{'would ' if dry_run else ''}{verb}: {destination}" + (f" (backup: {backup})" if backup else ""))
        if not dry_run:
            _publish(kind, destination, source, backup)
    return actions


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    install_parser = commands.add_parser("install", help="install one skill without changing prompts")
    install_parser.add_argument("--to", type=Path, required=True, help="host's skills directory")
    install_parser.add_argument("--skill", default="coresearch", choices=skills())
    install_parser.add_argument("--link", action="store_true", help="link to this checkout instead of copying")
    install_parser.add_argument("--dry-run", action="store_true")
    host_parser = commands.add_parser("host", help="install or check the shared instructions, skills and tools")
    host_parser.add_argument("action", choices=("install", "check", "render"))
    host_parser.add_argument("--host", action="append", choices=sorted(HOSTS), help="repeatable; default: all hosts")
    host_parser.add_argument("--home", type=Path, default=Path.home())
    host_parser.add_argument("--replace", action="store_true", help="back up and replace files this tool did not generate")
    host_parser.add_argument("--dry-run", action="store_true")
    init_parser = commands.add_parser("init", help="create research/brief.md; optional for any workflow")
    init_parser.add_argument("project", type=Path, nargs="?", default=Path.cwd())
    init_parser.add_argument("--question")
    init_parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args(argv)
    try:
        if args.command == "host":
            hosts = args.host or sorted(HOSTS)
            if args.action == "render":
                print("\n".join(render(host) for host in hosts), end="")
                return 0
            if args.action == "check":
                problems = host_check(args.home, hosts)
                print("\n".join(problems) if problems else "All managed files match this checkout.")
                return 1 if problems else 0
            actions = host_install(args.home, hosts, replace=args.replace, dry_run=args.dry_run)
            print("\n".join(actions) if actions else "Nothing to change.")
            return 2 if any(action.startswith("preserved") for action in actions) else 0
        if args.command == "install":
            result = install(args.to, link=args.link, dry_run=args.dry_run, skill=args.skill)
        else:
            result = initialize(args.project, question=args.question, dry_run=args.dry_run)
        print(result)
        return 0
    except (OSError, ValueError) as error:
        print(f"coresearch: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
