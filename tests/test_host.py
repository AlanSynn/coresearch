"""The host command: generated instruction files, linked skills and tools, preservation of foreign files."""
import os
import shutil
import stat
import tempfile
import unittest
from pathlib import Path
from unittest import mock

from test_install import installer

ROOT = Path(__file__).resolve().parents[1]


class HostTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.home = Path(self.temporary.name)

    def tearDown(self):
        self.temporary.cleanup()

    def test_install_writes_every_host_and_is_idempotent(self):
        actions = installer.host_install(self.home, sorted(installer.HOSTS))
        self.assertTrue(actions)
        self.assertEqual(installer.host_check(self.home, sorted(installer.HOSTS)), [])
        self.assertEqual(installer.host_install(self.home, sorted(installer.HOSTS)), [])
        claude = (self.home / ".claude/CLAUDE.md").read_text()
        self.assertTrue(claude.startswith("<!-- Generated by coresearch"))
        self.assertIn("## Claude Code", claude)
        self.assertNotIn("## Codex", claude)
        for name in installer.skills():
            self.assertEqual((self.home / ".claude/skills" / name).resolve(), (ROOT / "skills" / name).resolve())
            self.assertEqual((self.home / ".codex/skills" / name).resolve(), (ROOT / "skills" / name).resolve())
        self.assertTrue((self.home / ".local/bin/glm-delegate").resolve().samefile(ROOT / "skills/glm-delegate/scripts/glm-delegate"))
        self.assertTrue((self.home / ".codex/rules/coresearch.rules").resolve().samefile(ROOT / "host/codex.rules"))

    def test_foreign_instructions_are_preserved_then_backed_up_on_replace(self):
        target = self.home / ".codex/AGENTS.md"
        target.parent.mkdir(parents=True)
        target.write_text("hand-written\n")
        actions = installer.host_install(self.home, ["codex"])
        self.assertTrue(any(action.startswith("preserved") for action in actions))
        self.assertEqual(target.read_text(), "hand-written\n")
        self.assertIn(f"not generated by coresearch or edited by hand: {target}", installer.host_check(self.home, ["codex"]))
        installer.host_install(self.home, ["codex"], replace=True)
        self.assertEqual(target.read_text(), installer.render("codex"))
        backups = list((self.home / installer.BACKUPS).glob("*/.codex/AGENTS.md"))
        self.assertEqual([path.read_text() for path in backups], ["hand-written\n"])

    def test_hand_edited_generated_file_is_preserved(self):
        target = self.home / ".claude/CLAUDE.md"
        target.parent.mkdir(parents=True)
        target.write_text(installer.render("claude") + "- my own line\n")
        actions = installer.host_install(self.home, ["claude"])
        self.assertIn(f"preserved (use --replace to back up and replace): {target}", actions)
        self.assertTrue(target.read_text().endswith("- my own line\n"))

    def test_outdated_generated_file_is_updated_without_backup(self):
        target = self.home / ".pi/agent/AGENTS.md"
        target.parent.mkdir(parents=True)
        body = "an older core\n"
        target.write_text(installer.HEADER.format(delta="pi.md", digest=installer._digest(body)) + body)
        self.assertIn(f"outdated: {target}", installer.host_check(self.home, ["pi"]))
        installer.host_install(self.home, ["pi"])
        self.assertEqual(target.read_text(), installer.render("pi"))
        self.assertFalse((self.home / installer.BACKUPS).exists())

    def test_generated_file_behind_a_link_is_rewritten_in_place(self):
        dotfiles = self.home / "dotfiles/AGENTS.md"
        dotfiles.parent.mkdir(parents=True)
        body = "an older core\n"
        dotfiles.write_text(installer.HEADER.format(delta="codex.md", digest=installer._digest(body)) + body)
        target = self.home / ".codex/AGENTS.md"
        target.parent.mkdir(parents=True)
        target.symlink_to(dotfiles)
        installer.host_install(self.home, ["codex"])
        self.assertTrue(target.is_symlink())
        self.assertEqual(dotfiles.read_text(), installer.render("codex"))

    def test_skills_reached_through_a_linked_parent_are_left_in_place(self):
        checkout = self.home / "checkout"
        shutil.copytree(ROOT / "skills", checkout / "skills")
        shutil.copytree(ROOT / "host", checkout / "host")
        (self.home / ".codex").mkdir()
        (self.home / ".codex/skills").symlink_to(checkout / "skills", target_is_directory=True)
        with mock.patch.object(installer, "ROOT", checkout), mock.patch.object(installer, "HOST", checkout / "host"):
            actions = installer.host_install(self.home, ["codex"], replace=True)
        self.assertFalse(any("/.codex/skills/" in action for action in actions), actions)
        self.assertTrue((checkout / "skills/coresearch/SKILL.md").is_file())

    def test_foreign_skill_is_backed_up_outside_the_skills_directory(self):
        foreign = self.home / ".claude/skills/coresearch"
        foreign.mkdir(parents=True)
        (foreign / "SKILL.md").write_text("---\nname: coresearch\n---\nold copy\n")
        installer.host_install(self.home, ["claude"], replace=True)
        self.assertTrue(foreign.is_symlink())
        self.assertEqual(sorted(path.name for path in foreign.parent.iterdir()), sorted(installer.skills()))
        self.assertEqual(len(list((self.home / installer.BACKUPS).glob("*/.claude/skills/coresearch/SKILL.md"))), 1)

    def test_permission_rules_are_added_once_and_other_settings_kept(self):
        settings = self.home / ".claude/settings.json"
        settings.parent.mkdir(parents=True)
        settings.write_text('{"theme": "dark", "permissions": {"ask": ["Bash(rm *)"]}}\n')
        wanted = installer.json.loads((ROOT / "host/claude.permissions.json").read_text())["ask"]
        self.assertTrue(any(p.startswith("missing permission rules") for p in installer.host_check(self.home, ["claude"])))
        installer.host_install(self.home, ["claude"])
        data = installer.json.loads(settings.read_text())
        self.assertEqual(data["theme"], "dark")
        self.assertEqual(data["permissions"]["ask"], ["Bash(rm *)"] + wanted)
        self.assertEqual(len(list((self.home / installer.BACKUPS).glob("*/.claude/settings.json"))), 1)
        self.assertEqual(installer.host_install(self.home, ["claude"]), [])
        self.assertEqual(installer.host_check(self.home, ["claude"]), [])

    def test_unusable_settings_are_left_alone(self):
        settings = self.home / ".claude/settings.json"
        settings.parent.mkdir(parents=True)
        for text in ("not json", '{"permissions": {"ask": "Bash(git push *)"}}'):
            with self.subTest(text=text):
                settings.write_text(text)
                actions = installer.host_install(self.home, ["claude"])
                self.assertIn("preserved (fix by hand)", "\n".join(actions))
                self.assertEqual(settings.read_text(), text)

    def test_settings_keep_their_link_and_permissions(self):
        real = self.home / "dotfiles/settings.json"
        real.parent.mkdir(parents=True)
        real.write_text("{}\n")
        os.chmod(real, 0o600)
        settings = self.home / ".claude/settings.json"
        settings.parent.mkdir(parents=True)
        settings.symlink_to(real)
        installer.host_install(self.home, ["claude"])
        self.assertTrue(settings.is_symlink())
        self.assertIn("Bash(git push *)", real.read_text())
        self.assertEqual(stat.S_IMODE(real.stat().st_mode), 0o600)

    def test_dry_run_writes_nothing(self):
        actions = installer.host_install(self.home, sorted(installer.HOSTS), dry_run=True)
        self.assertTrue(all(action.startswith("would ") for action in actions))
        self.assertEqual(list(self.home.iterdir()), [])

    def test_rendered_instructions_stay_small(self):
        for host in installer.HOSTS:
            with self.subTest(host=host):
                text = installer.render(host)
                self.assertLess(len(text.splitlines()), 120)
                # Codex stops reading instructions at 32 KiB across the global and project files.
                self.assertLess(len(text.encode()), 8 * 1024)


if __name__ == "__main__":
    unittest.main()
